    private void ConfirmaAtualizacaoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_ConfirmaAtualizacaoActionPerformed
    String CPF = tCPF.getText();
    String Op = tOpcao.getSelectedItem().toString();
    EnderecoC end = new EnderecoC();
    if (Op == "Estado"){
        String Item = tItem.getText();
        end.AtualizaClientesEstado(CPF, Item);
    }
    if(Op == "Cidade")
    {
        String Item = tItem.getText();
        end.AtualizaClientesCidade(CPF, Item);
    }
    if(Op == "Cep"){
        String Item = tItem.getText();
        end.AtualizaClientesCep(CPF, Item);
    }
    if(Op == "Bairro"){
        String Item = tItem.getText();
        end.AtualizaClientesBairro(CPF, Item);
    }
    if(Op == "Rua"){
        String Item = tItem.getText();
        end.AtualizaClientesRua(CPF, Item);
    }
    if(Op == "Número"){
        int Item = Integer.parseInt(tItem.getText());
        end.AtualizaClientesNumero(CPF, Item);
    }
        
        
        
    dispose();
    new AtualizaEnderecoConcluido().setVisible(true);
    }//GEN-LAST:event_ConfirmaAtualizacaoActionPerformed

